import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';

import { Prisma, PrismaClient } from '@prisma/client';
import { describe, expect, it } from 'vitest';

const history = resolve('../backend/src/main/resources/db/migration');
const migrationDirectory = resolve('db/postgresql/migration');
const names = readdirSync(migrationDirectory).sort((a, b) =>
  Number(a.match(/^V(\d+)/)?.[1]) - Number(b.match(/^V(\d+)/)?.[1]));
const sql = names.map((name) => readFileSync(resolve(migrationDirectory, name), 'utf8')).join('\n');
const schema = readFileSync(resolve('prisma/schema.prisma'), 'utf8');

// Offline checks: these do not connect to any database or execute migration SQL.
describe('PostgreSQL migration contract', () => {
  it('preserves the 15 historical MySQL files and the exact V4 seed', () => {
    const hashes = JSON.parse(readFileSync('db/postgresql/mysql-source-sha256.json', 'utf8')) as Record<string, string>;
    expect(names).toHaveLength(15);
    expect(names.map((name) => Number(name.match(/^V(\d+)/)?.[1]))).toEqual(Array.from({ length: 15 }, (_, i) => i + 1));
    for (const name of names) {
      expect(createHash('sha256').update(readFileSync(resolve(history, name))).digest('hex')).toBe(hashes[name]);
    }
    expect(readFileSync(resolve(migrationDirectory, 'V4__seed_products.sql'), 'utf8'))
      .toBe(readFileSync(resolve(history, 'V4__seed_products.sql'), 'utf8'));
  });

  it('uses PostgreSQL identity, types and named indexes without MySQL syntax', () => {
    expect(sql).not.toMatch(/AUTO_INCREMENT|\bUNSIGNED\b|\bAFTER\b|\bUNIQUE KEY\b|\bKEY idx_|\bINDEX idx_\w+\s*\(/);
    expect(sql.match(/GENERATED BY DEFAULT AS IDENTITY/g)).toHaveLength(14);
    expect(sql).toContain('CHECK (stock_quantity >= 0)');
    expect(schema).toContain('provider = "postgresql"');
    expect(schema).not.toContain('@db.UnsignedInt');
    expect(readFileSync('prisma/schema.mysql.prisma', 'utf8')).toContain('provider = "mysql"');
  });

  it('preserves every historical named constraint and index', () => {
    const historicalSql = names.map((name) => readFileSync(resolve(history, name), 'utf8')).join('\n');
    const identifiers = [...historicalSql.matchAll(/\b(?:CONSTRAINT|INDEX|KEY)\s+((?:fk_|uk_|idx_)\w+)/g)].map((match) => match[1]);
    for (const identifier of identifiers) {
      expect(sql).toMatch(new RegExp(`\\b${identifier}\\b`));
      expect(schema).toContain(`map: "${identifier}"`);
    }
  });

  it('maps every generated Prisma scalar field to a migrated column', () => {
    expect(Prisma.dmmf.datamodel.models).toHaveLength(14);
    for (const model of Prisma.dmmf.datamodel.models) {
      const table = model.dbName ?? model.name;
      const create = sql.match(new RegExp(`CREATE TABLE ${table} \\(([\\s\\S]*?)\\n\\);`))?.[1];
      expect(create, table).toBeDefined();
      const alterations = [...sql.matchAll(new RegExp(`ALTER TABLE ${table}\\s+([\\s\\S]*?);`, 'g'))].map((match) => match[1]).join('\n');
      for (const field of model.fields.filter((field) => field.kind !== 'object')) {
        expect(`${create}\n${alterations}`, `${table}.${field.name}`)
          .toMatch(new RegExp(`\\b${field.dbName ?? field.name}\\s+(BIGINT|INTEGER|VARCHAR|TEXT|BOOLEAN|TIMESTAMP|DECIMAL)\\b`));
      }
    }
  });

  it('constructs the generated client with a PostgreSQL datasource without connecting', async () => {
    const client = new PrismaClient({ datasourceUrl: 'postgresql://test:test@127.0.0.1:5432/sarakusetu_test' });
    expect(client.product.findMany).toBeTypeOf('function');
    expect(client.$transaction).toBeTypeOf('function');
    await client.$disconnect();
  });
});

// Explicit opt-in only; never use DATABASE_URL (which may point at production).
// The user must create/migrate this local test database separately with Flyway.
const testUrl = process.env.POSTGRES_TEST_DATABASE_URL;
it.skipIf(!testUrl)('connects and executes mapped queries against an existing local PostgreSQL test database', async () => {
  const url = new URL(testUrl!);
  if (!['postgresql:', 'postgres:'].includes(url.protocol) ||
      !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname) ||
      url.pathname !== '/sarakusetu_test') {
    throw new Error('Integration test requires a loopback PostgreSQL URL for sarakusetu_test.');
  }
  const client = new PrismaClient({ datasourceUrl: testUrl });
  try {
    await client.$connect();
    await client.$transaction(async (tx) => {
      await tx.$executeRaw`SET TRANSACTION READ ONLY`;
      expect(await tx.$queryRaw`SELECT 1 AS ok`).toEqual([{ ok: 1 }]);
      // Read every mapped table/column; includes exercise the backend's relations.
      await tx.customer.findMany({ take: 1, include: { otpVerifications: true, cart: true } });
      await tx.cart.findMany({ take: 1, include: { items: { include: { product: true } } } });
      await tx.order.findMany({ take: 1, include: { items: true, payment: true, customer: true, wholesaler: true } });
      await tx.wholesaler.findMany({ take: 1, include: { inventoryItems: true, otpVerifications: true, notifications: true } });
      await tx.admin.findMany({ take: 1, include: { otpVerifications: true, notifications: true } });
      await tx.product.findMany({ where: { active: true }, orderBy: { createdAt: 'desc' }, take: 1 });
      await tx.cartItem.findMany({ take: 1 });
      await tx.orderItem.findMany({ take: 1 });
      await tx.payment.findMany({ take: 1 });
      await tx.otpVerification.findMany({ take: 1 });
      await tx.wholesalerOtpVerification.findMany({ take: 1 });
      await tx.adminOtpVerification.findMany({ take: 1 });
      await tx.wholesalerInventory.findMany({ take: 1 });
      await tx.notification.findMany({ take: 1 });
    });
  } finally {
    await client.$disconnect();
  }
});
