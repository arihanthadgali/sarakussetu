CREATE TABLE wholesaler_otp_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wholesaler_id BIGINT NULL,
    phone_number VARCHAR(20) NOT NULL,
    otp_hash VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_wholesaler_otp_wholesaler
        FOREIGN KEY (wholesaler_id)
        REFERENCES wholesalers(id)
);

CREATE INDEX idx_wholesaler_otp_phone_verified_expiry ON wholesaler_otp_verifications (phone_number, verified, expires_at);
CREATE INDEX idx_wholesaler_otp_wholesaler_id ON wholesaler_otp_verifications (wholesaler_id);
