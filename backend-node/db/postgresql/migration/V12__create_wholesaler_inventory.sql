CREATE TABLE wholesaler_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wholesaler_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    stock_quantity INTEGER NOT NULL CONSTRAINT ck_wholesaler_inventory_stock_nonnegative CHECK (stock_quantity >= 0),
    unit VARCHAR(50) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,

    PRIMARY KEY (id),
    CONSTRAINT uk_wholesaler_inventory_wholesaler_product UNIQUE (wholesaler_id, product_id),
    CONSTRAINT fk_wholesaler_inventory_wholesaler
        FOREIGN KEY (wholesaler_id) REFERENCES wholesalers (id),
    CONSTRAINT fk_wholesaler_inventory_product
        FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_wholesaler_inventory_product_id ON wholesaler_inventory (product_id);
